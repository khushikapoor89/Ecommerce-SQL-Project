# 🛒 E-Commerce Sales Analytics (MySQL)

## 📌 Project Overview
This project analyzes e-commerce sales data using MySQL.
It focuses on sales performance, customer behavior, and revenue insights.

## 🧱 Database Schema
- Customers
- Products
- Orders
- Order_Items
- Payments

## 🔍 SQL Concepts Used
- JOINs
- GROUP BY & HAVING
- Subqueries
- Window Functions
- Views
- Indexing

## 📊 Key Analysis
- Total Sales
- Monthly Revenue
- Top Selling Products
- Repeat Customers
- High-Value Customers

## 🛠 Tools Used
- MySQL
- MySQL Workbench

## ▶️ How to Run
1. Run `schema.sql`
2. Run `data.sql`
3. Run `analysis_queries.sql`
